import { DialogueLine, OpponentLineup, StoryChapter, StoryEpisode } from '../types/game';
import { getCharacterById } from './characters';

interface EpisodeSeed {
  title: string;
  location: string;
  summary: string;
  rivalId: string;
  setterId: string;
  blockerId: string;
  teamName: string;
  dialogues: DialogueLine[];
}

function buildEpisode(
  chapterNumber: number,
  epNum: number,
  seed: EpisodeSeed,
  baseAi: number
): StoryEpisode {
  const isBoss = epNum === 12;
  const aiLevel = baseAi + epNum * 2 + (isBoss ? 6 : 0);
  const opponent: OpponentLineup = {
    teamName: seed.teamName,
    spikerId: seed.rivalId,
    setterId: seed.setterId,
    blockerId: seed.blockerId,
    aiLevel,
    isBoss,
    bossUltimateChargeRate: isBoss ? 1.55 + chapterNumber * 0.08 : 1.0 + chapterNumber * 0.03,
    bossPowerMultiplier: isBoss ? 1.18 + chapterNumber * 0.03 : 1.0,
  };

  return {
    id: `c${chapterNumber}-e${epNum}`,
    chapterNumber,
    episodeNumber: epNum,
    title: seed.title,
    location: seed.location,
    summary: seed.summary,
    dialogues: seed.dialogues,
    opponent,
    rewardCoins: 100, // Base 100 coins every match + bonus in match screen
    rewardExp: 45 + chapterNumber * 18 + epNum * 4 + (isBoss ? 60 : 0),
  };
}

const d = (
  speakerId: string,
  side: 'left' | 'right',
  emotion: DialogueLine['emotion'],
  text: string,
  actionTag?: string
): DialogueLine => {
  const char = getCharacterById(speakerId);
  return {
    speakerId,
    speakerName: char.name,
    side,
    emotion,
    text,
    actionTag,
  };
};

