export const CHARACTER_MAP: Record<string, CharacterDef> = Object.fromEntries(
  CHARACTERS.map((c) => [c.id, c])
);

export const GACHA_POOL = CHARACTERS.filter((c) => c.isGachaPool);

export function getCharacterById(id: string): CharacterDef {
  return CHARACTER_MAP[id] || CHARACTERS[0];
}

export function getExpForNextLevel(level: number): number {
  return Math.floor(80 + level * 45 + level * level * 8);
}

export function getEffectiveStats(char: CharacterDef, level: number) {
  const mult = 1 + (level - 1) * 0.065;
  return {
    power: Math.round(char.baseStats.power * mult),
    speed: Math.round(char.baseStats.speed * mult),
    technique: Math.round(char.baseStats.technique * mult),
    defense: Math.round(char.baseStats.defense * mult),
  };
}
